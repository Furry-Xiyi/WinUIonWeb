const glyphsByValue = new Map(Object.values(symbolGlyphs))

export const resolveSymbolGlyph = (value: unknown): string => {
  const text = String(value ?? '').trim()
  const entry = symbolGlyphs[text]
  const numeric = typeof value === 'number' ? value : /^(?:\d+|0x[0-9a-f]+)$/i.test(text) ? Number(text) : NaN
  const codePoint = entry?.[1] ?? glyphsByValue.get(numeric) ?? numeric
  return Number.isInteger(codePoint) && codePoint >= 0 && codePoint <= 0xffff
    ? String.fromCharCode(codePoint)
    : ''
}
